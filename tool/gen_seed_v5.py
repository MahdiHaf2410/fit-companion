"""Generates lib/core/database/seed_v5.dart from tool/seed_v5_data.py (checks ids/names against older seeds)."""
import os, re, runpy
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
EX = runpy.run_path(os.path.join(root, 'tool', 'seed_v5_data.py'))['EX']
old_ids, old_names = set(), set()
for f in ['seed_data.dart', 'seed_v3.dart', 'seed_v4.dart']:
    s = open(os.path.join(root, 'lib', 'core', 'database', f), encoding='utf-8').read()
    for m in re.finditer(r"'(ex_[a-z0-9_]+)'", s):
        old_ids.add(m.group(1))
    for line in s.splitlines():
        if "('ex_" in line and "', '" in line:
            old_names.add(line.split("', '")[1].replace("\'", "'").lower())
ids = [e[0] for e in EX]
assert len(ids) == len(set(ids)), 'duplicate id in v5'
clash = [i for i in ids if i in old_ids]
assert not clash, f'id already used: {clash}'
same = [e[1] for e in EX if e[1].lower() in old_names]
assert not same, f'name already exists: {same}'
groups = {'chest', 'back', 'shoulders', 'arms', 'legs', 'core', 'cardio'}
equip = {'barbell', 'dumbbell', 'cable', 'machine', 'bodyweight', 'kettlebell', 'band', 'other'}
for e in EX:
    assert e[3] in groups and e[4] in equip and e[5] in ('compound', 'isolation'), e
esc = lambda s: s.replace("\\", "\\\\").replace("'", "\'")
lines = [
    '// GENERATED by tool/gen_seed_v5.py from tool/seed_v5_data.py. Do not edit by hand.',
    '/// v5 seed: extended exercise library (inserted with insertOrIgnore on every start).',
    '/// Tuple: (id, English name, Arabic name, muscleGroup, equipment, type)',
    'class SeedV5 {',
    '  SeedV5._();',
    '',
    '  static const exercises = <(String, String, String, String, String, String)>[',
]
for e in EX:
    lines.append("    (" + ", ".join(f"'{esc(x)}'" for x in e) + "),")
lines += ['  ];', '}', '']
open(os.path.join(root, 'lib', 'core', 'database', 'seed_v5.dart'), 'w', encoding='utf-8', newline='\n').write('\n'.join(lines))
print('seed_v5:', len(EX), 'exercises')
